import {spawn} from 'node:child_process';
import {mkdir,writeFile} from 'node:fs/promises';
import {resolve,join} from 'node:path';
const root=resolve(import.meta.dirname,'..'),home=join(root,'.local/native-smoke/home');
await mkdir(home,{recursive:true});
const version=JSON.parse(await (await import('node:fs/promises')).readFile(join(root,'package.json'),'utf8')).version;
const executable=process.env.YOUDUB2BI_SMOKE_EXECUTABLE || join(root,'dist',`release-${version}`,'win-unpacked/You2Bi.exe');
const env={...process.env,YOUDUB2BI_HOME:home,YOUDUB2BI_BACKGROUND_SMOKE:'1',YOUDUB_TEST_SKIP_SETUP:'1',YOUDUB_TEST_PYTHON:process.env.YOUDUB_TEST_PYTHON};
if(!env.YOUDUB_TEST_PYTHON)throw new Error('Set YOUDUB_TEST_PYTHON to the private Python executable');
delete env.ELECTRON_RUN_AS_NODE;
const child=spawn(executable,[`--user-data-dir=${join(root,'.local/native-smoke/user-data')}`],{env,windowsHide:true,stdio:['ignore','pipe','pipe']});
let output='';child.stdout.on('data',chunk=>output+=chunk);child.stderr.on('data',chunk=>output+=chunk);
const timeout=setTimeout(()=>child.kill(),90000);
const result=await new Promise((resolve,reject)=>{child.on('error',reject);child.on('exit',(code,signal)=>resolve({code,signal}));});clearTimeout(timeout);
const log=output.replace(/(token[=:]\s*)[^\s&"']+/gi,'$1[redacted]');
await writeFile(join(root,'.local/logs/native-smoke.log'),log);
if(result.code!==0 || !output.includes('You2Bi desktop ready') || /preload-error|Cannot find module|render-process-gone/.test(output))throw new Error(`Native smoke failed (${result.code}): ${log.slice(-6000)}`);
await writeFile(join(root,'artifacts/native-smoke.json'),JSON.stringify({passed:true,...result,hidden:true,isolated:true,version},null,2));
console.log('Packaged You2Bi: hidden desktop, Host, renderer navigation and clean shutdown passed.');
